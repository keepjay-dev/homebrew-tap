# Write Formula/keepjay.rb for a Keepjay release: the newest one, or $1 (e.g. 0.2.0-alpha.3).
# The checksums come from the release's own SHA256SUMS.txt.
set -eu

REPO="keepjay-dev/keepjay"
cd "$(dirname "$0")/.."

api() {
    if [ -n "${GITHUB_TOKEN:-}" ]; then
        curl -fsSL --retry 3 -H "Authorization: Bearer $GITHUB_TOKEN" "$1"
    else
        curl -fsSL --retry 3 "$1"
    fi
}

version=${1:-}
version=${version#v}
if [ -z "$version" ]; then
    # Every release so far is a pre-release, which /releases/latest skips.
    version=$(api "https://api.github.com/repos/$REPO/releases?per_page=1" |
        sed -n 's/.*"tag_name": *"v\([^"]*\)".*/\1/p' | head -n 1)
fi
[ -n "$version" ] || { echo "update-formula.sh: no release found" >&2; exit 1; }

base="https://github.com/$REPO/releases/download/v$version"
sums=$(curl -fsSL --retry 3 "$base/SHA256SUMS.txt")
sum() {
    s=$(printf '%s\n' "$sums" | awk -v f="keepjay-$version-$1.tar.gz" '$2 == f { print $1 }')
    [ -n "$s" ] || { echo "update-formula.sh: no $1 build in v$version" >&2; exit 1; }
    printf '%s' "$s"
}
arm=$(sum aarch64-apple-darwin)
intel=$(sum x86_64-apple-darwin)
linux=$(sum x86_64-unknown-linux-musl)

cat > Formula/keepjay.rb <<RUBY
# SPDX-License-Identifier: AGPL-3.0-or-later
# Generated by scripts/update-formula.sh from the v$version release; don't edit by hand.
class Keepjay < Formula
  desc "Local-first spaced repetition with flashcards in your code comments"
  homepage "https://github.com/$REPO"
  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
      url "$base/keepjay-$version-aarch64-apple-darwin.tar.gz"
      sha256 "$arm"
    end
    on_intel do
      url "$base/keepjay-$version-x86_64-apple-darwin.tar.gz"
      sha256 "$intel"
    end
  end

  on_linux do
    on_intel do
      url "$base/keepjay-$version-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux"
    end
  end

  def install
    bin.install "keepjay"
    # The short alias (CLI-018). Homebrew never overwrites another formula's kj: it stops
    # and names the conflict instead.
    bin.install_symlink "keepjay" => "kj"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/keepjay --version")
    ENV["KEEPJAY_DATA_DIR"] = (testpath/"data").to_s
    system bin/"keepjay", "init"
    assert_match "workspaces", shell_output("#{bin}/kj status --json")
  end
end
RUBY
echo "Formula/keepjay.rb: v$version"
